#!/usr/bin/env python3
"""Build src/wordmarks.js: each paper's own nameplate as vector paths.

  * The Stanford Daily: their official nameplate SVG, used as published. Download it with
        curl -o stanford-nameplate.svg https://stanforddaily.com/wp-content/uploads/2021/12/StanfordDailyLogo-01.svg
    (16 paths, one fill; we take the paths and recolour them in render.js).
  * The Daily Californian: no downloadable file was available (dailycal.org blocks automated
    requests), so the nameplate is traced from a clean black-on-white capture of the real
    nameplate: the site's slide-out menu header, screenshot cropped to the lettering with a few
    pixels of margin. Replace this with the paper's official SVG if they have one: just paste
    its path data into src/wordmarks.js as { d, x, y, w, h, rule: 'nonzero' }.

    pip install pillow potracer numpy svgpathtools
    python3 scripts/trace-wordmarks.py <dailycal-nameplate-crop.png> <stanford-nameplate.svg>
"""
import json, pathlib, re, sys
import numpy as np
from PIL import Image
import potrace
from svgpathtools import parse_path

ROOT = pathlib.Path(__file__).resolve().parent.parent
UP = 4   # upscale before thresholding so the curve fit is smooth

def trace_dark(path):
    im = Image.open(path).convert("L")
    big = im.resize((im.width * UP, im.height * UP), Image.LANCZOS)
    a = np.array(big)
    ink = a < 128
    ys, xs = np.where(ink)
    x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    # potracer traces the cells that are False, so hand it "is paper" (True where light).
    plist = potrace.Bitmap(a >= 128).trace(turdsize=10, alphamax=1.0, opticurve=True, opttolerance=0.3)
    f = lambda p: f"{(p.x - x0) / UP:.2f} {(p.y - y0) / UP:.2f}"
    d = []
    for curve in plist:
        d.append("M" + f(curve.start_point))
        for seg in curve.segments:
            if seg.is_corner: d.append("L" + f(seg.c) + "L" + f(seg.end_point))
            else: d.append("C" + f(seg.c1) + " " + f(seg.c2) + " " + f(seg.end_point))
        d.append("Z")
    h = round((y1 - y0) / UP, 2)
    # Daily Cal's nameplate is all capitals / small capitals sitting on one baseline with no descenders:
    # the top is the cap line and the baseline is the bottom.
    return {"d": "".join(d), "x": 0, "y": 0, "w": round((x1 - x0) / UP, 2), "h": h, "rule": "evenodd", "top": 0, "base": h}

def from_svg(path):
    svg = pathlib.Path(path).read_text(encoding="utf-8")
    ds = re.findall(r'<path[^>]*?\sd="([^"]+)"', svg)
    d = "".join(ds)
    xmin, xmax, ymin, ymax = parse_path(d).bbox()
    r = lambda v: round(v, 2)
    # The artwork is one path per letter. Top = the tallest letter's top; baseline = the median bottom of
    # the letters (descenders such as the y and h tails sit below it, overshoot is a few tenths of a unit).
    boxes = [parse_path(p).bbox() for p in ds]
    top = min(b[2] for b in boxes)
    base = sorted(b[3] for b in boxes)[len(boxes) // 2]
    return {"d": d, "x": r(xmin), "y": r(ymin), "w": r(xmax - xmin), "h": r(ymax - ymin), "rule": "nonzero", "top": r(top), "base": r(base)}

if len(sys.argv) != 3: sys.exit(__doc__)
words = {"cal": trace_dark(sys.argv[1]), "stanford": from_svg(sys.argv[2])}
for k, v in words.items():
    print(f"{k}: {v['w']}x{v['h']} (aspect {v['w']/v['h']:.1f}), path {len(v['d']):,} chars", file=sys.stderr)
js = ("// GENERATED by scripts/trace-wordmarks.py — each paper's nameplate as vector paths.\n"
      "// Stanford Daily: its own published SVG. Daily Cal: traced from its site's nameplate (replace with the\n"
      "// official SVG if available). These are the papers' trademarks; each should approve their use.\n"
      f"export const WORDMARKS = {json.dumps(words, separators=(',', ':'))};\n")
(ROOT / "src" / "wordmarks.js").write_text(js)
print(f"wrote src/wordmarks.js ({len(js):,} bytes)", file=sys.stderr)
