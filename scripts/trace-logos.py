#!/usr/bin/env python3
"""Trace the white marks from the papers' square avatars into vector paths -> src/logos.js.

Both avatars are a white mark on a flat colour. We threshold the mark, upscale first so the
curve fitting is smooth, and trace it with potrace. The output is a single path per logo in
the mark's own pixel units (origin at the mark's top-left), drawn white on a team-colour tile
by src/render.js. Vector means crisp at any size and nothing to load.

    pip install pillow potracer numpy
    python3 scripts/trace-logos.py <daily-cal-avatar.jpg> <stanford-daily-avatar.jpg>

Prefer official vector logos if either paper has them: replace the `d` strings in src/logos.js.
"""
import json, pathlib, sys
import numpy as np
from PIL import Image
import potrace

ROOT = pathlib.Path(__file__).resolve().parent.parent
UP = 3  # upscale factor before thresholding/tracing

def lum(rgb): return 0.299 * rgb[0] + 0.587 * rgb[1] + 0.114 * rgb[2]

def trace(path):
    im = Image.open(path).convert("RGB")
    bg = im.getpixel((6, 6))
    thr = (lum(bg) + 255) / 2                     # halfway between the background and white
    big = im.resize((im.width * UP, im.height * UP), Image.LANCZOS)
    mask = np.array(big.convert("L")) > thr       # True = the white mark (potracer traces the opposite, hence ~mask below)
    ys, xs = np.where(mask)
    x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    plist = potrace.Bitmap(~mask).trace(turdsize=12, alphamax=1.0, opticurve=True, opttolerance=0.3)
    f = lambda p: f"{(p.x - x0) / UP:.2f} {(p.y - y0) / UP:.2f}"
    d = []
    for curve in plist:
        d.append("M" + f(curve.start_point))
        for seg in curve.segments:
            if seg.is_corner: d.append("L" + f(seg.c) + "L" + f(seg.end_point))
            else: d.append("C" + f(seg.c1) + " " + f(seg.c2) + " " + f(seg.end_point))
        d.append("Z")
    return {"w": round((x1 - x0) / UP, 2), "h": round((y1 - y0) / UP, 2), "d": "".join(d)}

if len(sys.argv) != 3: sys.exit(__doc__)
logos = {"cal": trace(sys.argv[1]), "stanford": trace(sys.argv[2])}
for k, v in logos.items(): print(f"{k}: mark {v['w']}x{v['h']}, path {len(v['d']):,} chars", file=sys.stderr)
js = ("// GENERATED by scripts/trace-logos.py — the white marks of The Daily Californian and The Stanford Daily\n"
      "// avatars as vector paths (origin = the mark's top-left, units = source pixels). Drawn white on a\n"
      "// team-colour tile by src/render.js. These are the papers' trademarks, reproduced for their joint Ink Bowl fundraiser; each paper should approve this use.\n"
      f"export const LOGOS = {json.dumps(logos, separators=(',', ':'))};\n")
(ROOT / "src" / "logos.js").write_text(js)
print(f"wrote src/logos.js ({len(js):,} bytes)", file=sys.stderr)
