#!/usr/bin/env python3
"""Turn the board's typefaces into outline data and emit src/glyphs.js.

WHY OUTLINES: the board is delivered as an SVG inside an <img>. Browsers paint such an
image once; if its text depends on an embedded font that is still decoding, the text is
simply invisible and the image never repaints (what happened on first load on phones).
Drawing every letter as a path removes the font dependency entirely, so the image looks
identical on first paint in every browser, in Givebutter, and in the PNG rasteriser.

Run after `npm install` (fonts come from @fontsource, SIL Open Font License):
    pip install fonttools brotli uharfbuzz && python3 scripts/build-glyphs.py
The output is committed, so the Worker build has no font step. Only change the charset or
fonts here, then regenerate.
"""
import json, pathlib, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
import uharfbuzz as hb

ROOT = pathlib.Path(__file__).resolve().parent.parent
CHARS = ("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
         "$,.'’:·—–-&%+()!? ")
FONTS = {
    # key: (source woff2, note)
    "d500": "node_modules/@fontsource/oswald/files/oswald-latin-500-normal.woff2",
    "d700": "node_modules/@fontsource/oswald/files/oswald-latin-700-normal.woff2",
    "s700i": "node_modules/@fontsource/playfair-display/files/playfair-display-latin-700-italic.woff2",
}

def num(v):
    v = round(v, 1)
    return int(v) if v == int(v) else v

out = {}
for key, rel in FONTS.items():
    path = ROOT / rel
    tt = TTFont(str(path))
    upm = tt["head"].unitsPerEm
    cmap = tt.getBestCmap()
    gs = tt.getGlyphSet()
    hbfont = hb.Font(hb.Face(hb.Blob(open(path, "rb").read()))) if False else None
    # uharfbuzz can't read woff2: save a plain TTF for shaping
    tmp = ROOT / "build-tmp.ttf"; tt.flavor = None; tt.save(str(tmp))
    face = hb.Face(hb.Blob(tmp.read_bytes())); hbfont = hb.Font(face)
    feats = {"kern": True, "liga": False, "clig": False, "calt": False}

    def adv(text):
        buf = hb.Buffer(); buf.add_str(text); buf.guess_segment_properties()
        hb.shape(hbfont, buf, feats)
        return [p.x_advance for p in buf.glyph_positions]

    glyphs = {}
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if name is None:
            print(f"  {key}: no glyph for {ch!r}", file=sys.stderr); continue
        pen = SVGPathPen(gs, ntos=lambda v: str(num(v)))
        gs[name].draw(pen)
        glyphs[ch] = [gs[name].width, pen.getCommands()]
    kern = {}
    for a in CHARS:
        if a not in glyphs or a == " ": continue
        solo = adv(a)[0]
        for b in CHARS:
            if b not in glyphs or b == " ": continue
            k = adv(a + b)[0] - solo
            if k: kern[a + b] = k
    out[key] = {"upm": upm, "glyphs": glyphs, "kern": kern}
    print(f"{key}: {len(glyphs)} glyphs, {len(kern)} kern pairs, upm {upm}", file=sys.stderr)
    tmp.unlink()

js = ("// GENERATED by scripts/build-glyphs.py — do not edit by hand.\n"
      "// Oswald and Playfair Display (SIL Open Font License 1.1) as outlines: [advance, SVG path] per character,\n"
      "// plus pair kerning, so the board draws its text as shapes and needs no web font at render time.\n"
      f"export const GLYPH_SETS = {json.dumps(out, ensure_ascii=False, separators=(',', ':'))};\n")
(ROOT / "src" / "glyphs.js").write_text(js)
print(f"wrote src/glyphs.js ({len(js):,} bytes)", file=sys.stderr)
