#!/usr/bin/env python3
"""Subset the board's typefaces to the glyphs it can render and emit src/fonts.js.

Run after `npm install` (fonts come from @fontsource packages, SIL Open Font
License) with `python3 scripts/subset-fonts.py`. The output is committed so the
Worker build has no font step. TTF is used for both the SVG @font-face and the
PNG rasteriser (resvg's font database reads TTF/OTF, not WOFF2).
"""
import base64, json, pathlib, sys
from fontTools.ttLib import TTFont
from fontTools.subset import Subsetter, Options

ROOT = pathlib.Path(__file__).resolve().parent.parent
CHARS = ("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
         "$,.'’:·—–-&%+()!? ")
FONTS = [
    # (family, weight, style, source woff2)
    ("Oswald", 500, "normal", "node_modules/@fontsource/oswald/files/oswald-latin-500-normal.woff2"),
    ("Oswald", 700, "normal", "node_modules/@fontsource/oswald/files/oswald-latin-700-normal.woff2"),
    ("Playfair Display", 700, "italic", "node_modules/@fontsource/playfair-display/files/playfair-display-latin-700-italic.woff2"),
]

def subset(path):
    f = TTFont(str(ROOT / path))
    opts = Options()
    opts.flavor = None            # plain TTF out
    opts.desubroutinize = True
    opts.name_IDs = ['*']; opts.name_legacy = True; opts.name_languages = ['*']
    opts.layout_features = ['kern', 'liga', 'calt']
    s = Subsetter(options=opts)
    s.populate(text=CHARS)
    s.subset(f)
    f.flavor = None
    out = ROOT / "build-tmp.ttf"
    f.save(str(out))
    data = out.read_bytes(); out.unlink()
    return data

entries = []
for family, weight, style, src in FONTS:
    data = subset(src)
    entries.append({"family": family, "weight": weight, "style": style,
                    "b64": base64.b64encode(data).decode("ascii"), "bytes": len(data)})
    print(f"{family} {weight} {style}: {len(data):,} bytes", file=sys.stderr)

css = "\n".join(
    f"@font-face{{font-family:'{e['family']}';font-weight:{e['weight']};font-style:{e['style']};"
    f"src:url(data:font/ttf;base64,{e['b64']}) format('truetype');}}" for e in entries)

js = ("// GENERATED by scripts/subset-fonts.py — do not edit by hand.\n"
      "// Oswald and Playfair Display, SIL Open Font License 1.1, subset to the board's glyphs.\n"
      f"export const FONT_FILES = {json.dumps([{k: e[k] for k in ('family','weight','style','b64')} for e in entries])};\n"
      f"export const FONT_CSS = {json.dumps(css)};\n"
      "export function fontBuffers() {\n"
      "  return FONT_FILES.map((f) => Uint8Array.from(atob(f.b64), (c) => c.charCodeAt(0)));\n"
      "}\n")
(ROOT / "src" / "fonts.js").write_text(js)
print(f"wrote src/fonts.js ({len(js):,} chars)", file=sys.stderr)
