// Measure each logo mark's and nameplate's "ink" (filled area, in its own path units squared) by rasterising
// it, and write src/ink.js. render.js uses these to size the two papers' marks for equal visual mass.
// Re-run after changing src/logos.js or src/wordmarks.js:   node scripts/measure-ink.cjs
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const { WORDMARKS } = await import('../src/wordmarks.js');
  const { LOGOS } = await import('../src/logos.js');
  const { chromium } = require('playwright');
  const br = await chromium.launch(); const pg = await br.newPage();
  const measure = (d, rule, w, h, x = 0, y = 0) => pg.evaluate(({ d, rule, w, h, x, y }) => {
    const K = 4, c = document.createElement('canvas'); c.width = Math.ceil((w + 4) * K); c.height = Math.ceil((h + 4) * K);
    const g = c.getContext('2d'); g.scale(K, K); g.translate(2 - x, 2 - y); g.fillStyle = '#000'; g.fill(new Path2D(d), rule);
    const px = g.getImageData(0, 0, c.width, c.height).data; let n = 0; for (let i = 3; i < px.length; i += 4) n += px[i] / 255;
    return n / (K * K);
  }, { d, rule, w, h, x, y });
  const out = { wordmarks: {}, logos: {} };
  for (const [k, m] of Object.entries(WORDMARKS)) out.wordmarks[k] = Math.round(await measure(m.d, m.rule, m.w, m.h, m.x, m.y));
  for (const [k, l] of Object.entries(LOGOS)) out.logos[k] = Math.round(await measure(l.d, 'evenodd', l.w, l.h));
  await br.close();
  const js = '// GENERATED by scripts/measure-ink.cjs: filled area of each mark and nameplate in its own path units squared.\n' +
    `export const INK_AREA = ${JSON.stringify(out)};\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'ink.js'), js);
  console.log('wrote src/ink.js', JSON.stringify(out));
})();
